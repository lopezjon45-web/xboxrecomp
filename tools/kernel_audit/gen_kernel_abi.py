"""
Write src/kernel/kernel_abi.inc, each xboxkrnl ordinal's calling convention and
the stack bytes its callee pops, from nxdk's import library sources.

    python3 tools/kernel_audit/gen_kernel_abi.py <nxdk>/lib/xboxkrnl          write the table
    python3 tools/kernel_audit/gen_kernel_abi.py <nxdk>/lib/xboxkrnl --check  exit 1 if it differs

Two nxdk files say the same thing in two ways, and both must agree before a row
is written: xboxkrnl.exe.def gives each ordinal's decorated name (Name@N is
stdcall with N argument bytes, @Name@N is fastcall, a bare name is cdecl or
DATA), and xboxkrnl.h gives the prototype the decoration was made from. The
header decides how many of a fastcall's bytes travel in ecx and edx and how many
on the stack, which the decoration cannot say.

The bridges pop what this table says (stdcall_args_for_ordinal), so a row here
is the only place an argument count is written down.
"""

import os
import re
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
OUT = os.path.join(ROOT, "src", "kernel", "kernel_abi.inc")
ORDINAL_MAX = 378

WIDE = {"LARGE_INTEGER", "ULARGE_INTEGER", "LONGLONG", "ULONGLONG"}


def parse_def(text):
    rows = {}
    for line in text.splitlines():
        m = re.match(r"\s+(@?)([A-Za-z_]\w*)(?:@(\d+))?\s+@\s*(\d+)\s+NONAME(\s+DATA)?\s*$", line)
        if not m:
            continue
        fast, name, nbytes, ordinal, data = m.groups()
        if data:
            conv = "data"
        elif fast:
            conv = "fastcall"
        elif nbytes is None:
            conv = "cdecl"
        else:
            conv = "stdcall"
        rows[int(ordinal)] = (name, conv, int(nbytes or 0))
    return rows


def param_bytes(param):
    param = re.sub(r"\b(IN|OUT|OPTIONAL|CONST|const|volatile|UNALIGNED|RESTRICTED_POINTER)\b", " ", param).strip()
    if "*" in param:
        return 4
    words = param.split()
    return 8 if words and words[0] in WIDE else 4


def parse_header(text):
    protos = {}
    for m in re.finditer(r"XBAPI\b[^;(]*?\b(NTAPI|FASTCALL|CDECL)\s+"
                         r"(?:__attribute__\s*\(\(\s*\w+\s*\)\)\s*|DECLSPEC_NORETURN\s+)*(\w+)\s*\(([^;]*?)\)\s*;",
                         text, re.S):
        conv, name, params = m.groups()
        params = re.sub(r"/\*.*?\*/|//[^\n]*", "", params, flags=re.S)
        args = [p.strip() for p in params.split(",") if p.strip()]
        if args in (["VOID"], ["void"]):
            args = []
        protos[name] = ({"NTAPI": "stdcall", "FASTCALL": "fastcall", "CDECL": "cdecl"}[conv], args)
    return protos


def abi_row(name, conv, nbytes, protos, errors):
    """(convention, stack bytes the callee pops, arguments in ecx/edx) for one export."""
    if conv == "data":
        return "DATA", 0, 0
    proto = protos.get(name)
    if proto is None:
        errors.append(f"{name}: in xboxkrnl.exe.def but no prototype in xboxkrnl.h")
        return "NONE", 0, 0
    hconv, args = proto
    if hconv != conv:
        errors.append(f"{name}: xboxkrnl.exe.def says {conv}, xboxkrnl.h says {hconv}")
    if conv == "cdecl":
        return "CDECL", 0, 0
    sizes = [param_bytes(a) for a in args]
    if sum(sizes) != nbytes:
        errors.append(f"{name}: xboxkrnl.exe.def says {nbytes} bytes, xboxkrnl.h's {len(args)} parameters make {sum(sizes)}")
    if conv == "stdcall":
        return "STDCALL", nbytes, 0
    # The first two arguments that fit a register go in ecx and edx; everything else is pushed.
    in_registers, stack = 0, 0
    for size in sizes:
        if size == 4 and in_registers < 2:
            in_registers += 1
        else:
            stack += size
    return "FASTCALL", stack, in_registers


def render(rows, protos, errors):
    lines = [
        "/* Generated by tools/kernel_audit/gen_kernel_abi.py from nxdk's lib/xboxkrnl/xboxkrnl.exe.def and",
        " * xboxkrnl.h. Index = ordinal: { convention, stack bytes the callee pops, arguments in ecx and edx }. */",
        f"static const struct kernel_abi k_kernel_abi[{ORDINAL_MAX + 1}] = {{",
    ]
    for o in range(ORDINAL_MAX + 1):
        if o not in rows:
            lines.append(f"    {{ KABI_NONE, 0, 0 }},   /* {o} */")
            continue
        name, conv, nbytes = rows[o]
        kind, stack, regs = abi_row(name, conv, nbytes, protos, errors)
        lines.append(f"    {{ KABI_{kind}, {stack}, {regs} }},   /* {o} {name} */")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    lib = argv[1]
    rows = parse_def(open(os.path.join(lib, "xboxkrnl.exe.def"), encoding="utf-8").read())
    protos = parse_header(open(os.path.join(lib, "xboxkrnl.h"), encoding="utf-8").read())
    if len(rows) < 360:
        print(f"only {len(rows)} exports parsed from xboxkrnl.exe.def")
        return 1
    errors = []
    text = render(rows, protos, errors)
    if errors:
        print("nxdk's def and header disagree:\n  " + "\n  ".join(errors))
        return 1
    if "--check" in argv:
        if open(OUT, encoding="utf-8").read() != text:
            print(f"{OUT} differs from nxdk's xboxkrnl prototypes: rerun gen_kernel_abi.py")
            return 1
        print(f"kernel_abi.inc matches nxdk ({len(rows)} exports)")
        return 0
    open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print(f"wrote {OUT} ({len(rows)} exports)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
